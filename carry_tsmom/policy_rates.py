def _parse(text: str) -> pd.Series:
    tok = text.split()
    dates = pd.to_datetime(tok[0::2])
    vals = [float(x) for x in tok[1::2]]
    s = pd.Series(vals, index=dates).sort_index()
    if s.index.has_duplicates:
        raise ValueError("duplicate change dates")
    return s


def policy_rates(index: pd.DatetimeIndex) -> pd.DataFrame:
    """Annual policy rates in decimal (0.0525 = 5.25%), step-forward-filled onto index."""
    out = {}
    for ccy, txt in _RAW.items():
        s = _parse(txt) / 100.0
        full = s.reindex(s.index.union(index)).ffill()
        out[ccy] = full.reindex(index)
    return pd.DataFrame(out, index=index)
